def fleet_error():
    wf = WF("fleet-error", "fleet-error", error=False)
    wf.add("Error Trigger", "n8n-nodes-base.errorTrigger", 1, {}, 0, 0)
    code(wf, "Format", r"""
const e = $input.first().json;
const wf = (e.workflow && e.workflow.name) || 'an unknown workflow';
const node = (e.execution && e.execution.lastNodeExecuted) || '';
const msg = String((e.execution && e.execution.error && e.execution.error.message) || 'no message').replace(/\s+/g, ' ').slice(0, 200);
const id = (e.execution && e.execution.id) || '';
const text = ('n8n workflow failed: ' + wf + (node ? ' at ' + node : '') + '. ' + msg + (id ? ' (run ' + id + ')' : '')).slice(0, 600);
return [{ json: { text, run: String(id).replace(/[^A-Za-z0-9_-]/g, '').slice(0, 40) } }];
""", 220, 0)
    # The error workflow sends straight to the control bot. It must not call fleet-event, because a broken fleet-event would loop.
    # Each alert has a real error output (onError plus a wired main[1]). A failed alert leaves a file. See D-041.
    http(wf, "Alert Slack", "POST", CONTROL + "/v1/slack/post", 440, -80, auth=CRED_ACTION,
         body="={{ JSON.stringify({ channel: 'alerts', text: ':warning: ' + $json.text, severity: 'warn' }) }}", onError="continueErrorOutput", **retry())
    http(wf, "Alert Owner", "POST", CONTROL + "/v1/notify", 440, 80, auth=CRED_ACTION,
         body="={{ JSON.stringify({ text: $json.text, severity: 'warn' }) }}", onError="continueErrorOutput", **retry())
    for key, label, y in (("slack", "Slack", -40), ("owner", "Owner", 120)):
        code(wf, "Unsent " + label, r"""
// This alert could not be sent. The control bot is down or does not accept the token. Leave one small file.
// The control bot reads the folder and sends the text when it can. The file name has only safe characters.
const f = $('Format').first().json;
const run = f.run || String(Date.now());
return [{ json: { file: 'alert-' + run + '-@CH@.json', channel: '@CH@', text: String(f.text || '').slice(0, 600), at: new Date().toISOString() } }];
""".replace("@CH@", key), 680, y)
    wf.add("Unsent To File", "n8n-nodes-base.convertToFile", 1.1, {"operation": "toJson", "mode": "each", "binaryPropertyName": "data",
                                                                    "options": {"fileName": "={{ $json.file }}"}}, 900, 40)
    wf.add("Keep Unsent Alert", "n8n-nodes-base.readWriteFile", 1.1, {"operation": "write", "fileName": "={{ '/home/node/files/unsent/' + $binary.data.fileName }}",
                                                                       "dataPropertyName": "data", "options": {}}, 1120, 40)
    wf.link("Error Trigger", "Format")
    wf.link("Format", "Alert Slack")
    wf.link("Format", "Alert Owner")
    wf.link("Alert Slack", "Unsent Slack", output=1)
    wf.link("Alert Owner", "Unsent Owner", output=1)
    wf.link("Unsent Slack", "Unsent To File")
    wf.link("Unsent Owner", "Unsent To File")
    wf.link("Unsent To File", "Keep Unsent Alert")
    return wf.build()


