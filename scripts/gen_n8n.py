def health_watch():
    wf = WF("health-watch", "health-watch", frequent=True)
    wf.add("Every 5 Minutes", "n8n-nodes-base.scheduleTrigger", 1.2, {"rule": {"interval": [{"field": "minutes", "minutesInterval": 5}]}}, 0, 0)
    targets = [("guard", PORTS["guard"], "/health"), ("reader", PORTS["reader"], "/health"), ("publisher", PORTS["publisher"], "/health"),
               ("deployer", PORTS["deployer"], "/health"), ("control", PORTS["control"], "/health"), ("router", PORTS["router"], "/api/health"),
               ("searxng", PORTS["searxng"], "/healthz")]
    listing = ",\n  ".join("{ name: '%s', url: '%s:%d%s' }" % (n, LOCAL, p, path) for n, p, path in targets)
    code(wf, "Targets", "const targets = [\n  %s\n];\nreturn targets.map(t => ({ json: t }));" % listing, 220, 0)
    http(wf, "Check", "GET", "={{ $json.url }}", 440, 0, timeout=5000, text=True, onError="continueRegularOutput")
    http(wf, "Fleet Status", "GET", CONTROL + "/v1/status", 660, 0, auth=CRED_ACTION, timeout=8000, onError="continueRegularOutput", executeOnce=True)
    code(wf, "Evaluate", r"""
const data = $getWorkflowStaticData('global');
data.fail = data.fail || {};
data.alerted = data.alerted || {};
const targets = $('Targets').all();
const checks = $('Check').all();
const status = $('Fleet Status').first().json || {};
const results = checks.map((c, i) => {
  const code = Number(c.json.statusCode || 0);
  return { name: targets[i].json.name, ok: !c.json.error && code >= 200 && code < 300, code };
});
// Units without an HTTP health path: the control bot reports their state.
const services = status.services || {};
for (const unit of ['gateway', 'events']) {
  if (unit in services) results.push({ name: unit, ok: services[unit] === 'active', code: 0 });
}
if (!status.services) results.push({ name: 'control-api', ok: false, code: 0 });
const events = [];
for (const r of results) {
  if (r.ok) {
    if (data.alerted[r.name]) {
      events.push({ type: 'health.recovered', severity: 'info', source: 'health-watch', title: r.name + ' is back', text: r.name + ' answers again.' });
    }
    data.fail[r.name] = 0;
    data.alerted[r.name] = false;
  } else {
    data.fail[r.name] = (data.fail[r.name] || 0) + 1;
    if (data.fail[r.name] >= 2 && !data.alerted[r.name]) {
      data.alerted[r.name] = true;
      events.push({ type: 'alert.health', severity: 'critical', source: 'health-watch', title: r.name + ' is down',
                    text: r.name + ' failed 2 checks in a row' + (r.code ? ' (status ' + r.code + ')' : '') + '.', fields: { service: r.name } });
    }
  }
}
return events.map(e => ({ json: e }));
""", 880, 0)
    http(wf, "Send Event", "POST", EVENT_URL, 1100, 0, auth=CRED_EVENT, body="={{ JSON.stringify($json) }}", **retry())
    code(wf, "Heartbeat", r"""
return [{ json: { checked: new Date().toISOString(), workflow: 'health-watch' } }];
""", 220, 200)
    wf.add("To File", "n8n-nodes-base.convertToFile", 1.1, {"operation": "toJson", "mode": "once", "binaryPropertyName": "data", "options": {"fileName": "health-watch.json"}}, 440, 200)
    wf.add("Write Heartbeat", "n8n-nodes-base.readWriteFile", 1.1, {"operation": "write", "fileName": "/home/node/files/heartbeat/health-watch.json",
                                                                     "dataPropertyName": "data", "options": {}}, 660, 200)
    wf.add("When Called", "n8n-nodes-base.executeWorkflowTrigger", 1.1, {"inputSource": "passthrough"}, 0, 400)      # /fleet run health-watch. See D-055.
    wf.link("Every 5 Minutes", "Targets")
    wf.link("When Called", "Targets")
    wf.link("Targets", "Check")
    wf.link("Check", "Fleet Status")
    wf.link("Fleet Status", "Evaluate")
    wf.link("Evaluate", "Send Event")
    wf.link("Every 5 Minutes", "Heartbeat")
    wf.link("Heartbeat", "To File")
    wf.link("To File", "Write Heartbeat")
    return wf.build()


