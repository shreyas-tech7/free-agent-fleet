#!/usr/bin/env python3
"""Generate the n8n workflows in n8n/workflows/*.json.

One script makes every workflow, so node ids stay stable, credentials are always named placeholders, and a test
can check that the committed files match. Edit this file, then run it. Do not edit the JSON by hand.

  gen_n8n.py            write the files
  gen_n8n.py --check    exit 1 when a file is out of date (a test runs this)

Placeholders that `fleetctl n8n bootstrap` resolves when it imports the workflows:
  FLEET_CRED:<name>   the id of the n8n credential with that name
  FLEET_WF:<name>     the id of the workflow with that name

Rules that the tests check: no legacy node, no Execute Command node, no secret in the JSON, loopback URLs only,
an error workflow on every workflow except fleet-error, and no success data kept for workflows that run often.
Prompt 3, Phase 2. See D-040.
"""
