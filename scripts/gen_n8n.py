def fetch_feed_sub():
    wf = WF("fleet-tool-fetch-feed", "fleet-tool-fetch-feed")
    wf.add("When Called", "n8n-nodes-base.executeWorkflowTrigger", 1.1, {"inputSource": "workflowInputs",
                                                                           "workflowInputs": {"values": [{"name": "url", "type": "string"}]}}, 0, 0)
    code(wf, "Validate", r"""
const ALLOWED = __ALLOWED__;
// The n8n Code sandbox has no URL class (checked on n8n 2.47.4, D-054). So the address is read by hand, with strict rules.
const raw = String($input.first().json.url || '').trim();
const parts = /^([A-Za-z][A-Za-z0-9+.-]*):\/\/([^\/?#]*)([^#]*)(#.*)?$/.exec(raw);
if (!parts || /[^\x21-\x7e]/.test(raw) || raw.indexOf('\\') !== -1) {
  return [{ json: { ok: false, error: 'The address is not valid.' } }];
}
const authority = parts[2];
if (parts[1].toLowerCase() !== 'https' || authority.indexOf('@') !== -1 || authority.indexOf(':') !== -1 || raw.length > 300) {
  return [{ json: { ok: false, error: 'Use a plain https address with no port and no login.' } }];
}
const host = authority.toLowerCase();
if (!host || ALLOWED.indexOf(host) === -1) {
  return [{ json: { ok: false, error: 'This host is not on the allowed list: ' + ALLOWED.join(', ') } }];
}
let rest = parts[3];
if (rest === '' || rest.charAt(0) === '?') rest = '/' + rest;
return [{ json: { ok: true, url: 'https://' + host + rest } }];
""".replace("__ALLOWED__", json.dumps(HOSTS)), 220, 0)
    if_true(wf, "Allowed", "$json.ok", 440, 0)
    wf.add("Fetch", "n8n-nodes-base.httpRequest", 4.5, {"method": "GET", "url": "={{ $json.url }}", "options": {
        "timeout": 15000, "redirect": {"redirect": {"followRedirects": False}},
        "response": {"response": {"responseFormat": "text", "neverError": False}}}}, 680, -80, onError="continueErrorOutput")
    wf.add("Parse XML", "n8n-nodes-base.xml", 1, {"mode": "xmlToJson", "dataPropertyName": "data", "options": {"explicitArray": False, "mergeAttrs": True}}, 900, -80)
    code(wf, "Items", r"""
const root = $input.first().json;
const arr = (x) => x === undefined || x === null ? [] : (Array.isArray(x) ? x : [x]);
const text = (x) => (typeof x === 'string' ? x : (x && (x._ || x['#text'])) || '');
const clean = (s, n) => String(s || '').replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim().slice(0, n);
const link = (l) => { const a = arr(l)[0]; return typeof a === 'string' ? a : (a && a.href) || ''; };
let items = [];
if (root.rss && root.rss.channel) {
  items = arr(root.rss.channel.item).map(i => ({ id: text(i.guid) || text(i.link), title: text(i.title), link: text(i.link), published: text(i.pubDate), summary: text(i.description) }));
} else if (root.feed) {
  items = arr(root.feed.entry).map(e => ({ id: text(e.id) || link(e.link), title: text(e.title), link: link(e.link), published: text(e.updated) || text(e.published), summary: text(e.summary) || text(e.content) }));
}
const data = $getWorkflowStaticData('global');
data.seen = data.seen || {};
const host = String($('Validate').first().json.url).split('/')[2];       // the Validate node made it: https://host/path
const seen = new Set(data.seen[host] || []);
const fresh = [];
for (const i of items.slice(0, 30)) {
  const id = String(i.id || i.link || '').slice(0, 200);
  if (!id || seen.has(id)) continue;
  seen.add(id);
  fresh.push({ id, title: clean(i.title, 200), link: String(i.link || '').slice(0, 300), published: String(i.published || '').slice(0, 40), summary: clean(i.summary, 300) });
}
data.seen[host] = Array.from(seen).slice(-300);
return fresh.slice(0, 20).map(i => ({ json: i }));
""", 1120, -80)
    http(wf, "Screen", "POST", GUARD + "/scan", 1340, -80, timeout=20000, onError="continueRegularOutput",
         body="={{ JSON.stringify({ text: (($json.title || '') + '\\n' + ($json.summary || '')).slice(0, 2000) }) }}")
    code(wf, "Filter", r"""
// An item goes on only when the injection screen says SAFE. No answer counts as not safe.
const items = $('Items').all();
const scans = $input.all();
const clean = [];
let blocked = 0;
let unscreened = 0;
scans.forEach((s, i) => {
  const label = s.json && s.json.label;
  if (label === 'SAFE') clean.push(items[i].json);
  else if (label) blocked++;
  else unscreened++;
});
return [{ json: { ok: true, items: clean, blocked, unscreened, total: items.length } }];
""", 1560, -80)
    code(wf, "Refuse", r"""
return [{ json: { ok: false, error: $input.first().json.error || 'The feed was not read.' } }];
""", 680, 120)
    code(wf, "Fetch Failed", r"""
return [{ json: { ok: false, error: 'The feed could not be read.' } }];
""", 900, 120)
    wf.link("When Called", "Validate")
    wf.link("Validate", "Allowed")
    wf.link("Allowed", "Fetch", output=0)
    wf.link("Allowed", "Refuse", output=1)
    wf.link("Fetch", "Parse XML", output=0)
    wf.link("Fetch", "Fetch Failed", output=1)
    wf.link("Parse XML", "Items")
    wf.link("Items", "Screen")
    wf.link("Screen", "Filter")
    return wf.build()


