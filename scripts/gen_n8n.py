import pathlib
import sys
import uuid

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "n8n" / "workflows"
NS = uuid.UUID("6f1c2d3e-4a5b-4c6d-8e7f-0a1b2c3d4e5f")
PORTS = yaml.safe_load((ROOT / "config" / "fleet.example.yaml").read_text())["ports"]
TZ = "America/Chicago"
LOCAL = "http://127.0.0.1"
CONTROL = "%s:%d" % (LOCAL, PORTS["control"])
GUARD = "%s:%d" % (LOCAL, PORTS["guard"])
N8N = "%s:%d" % (LOCAL, PORTS["n8n"])
EVENT_URL = "%s/webhook/fleet-event" % N8N
HOSTS = ["hnrss.org", "news.ycombinator.com", "github.com", "stackoverflow.com", "dev.to", "lobste.rs", "blog.cloudflare.com", "n8n.io"]

# Credentials. The value of each is made from a fleet secret by `fleetctl n8n bootstrap`.
CRED_EVENT = ("httpHeaderAuth", "fleet-event-token")       # header X-Fleet-Token: the event relay and n8n share it
CRED_ACTION = ("httpBearerAuth", "fleet-action-token")     # n8n calls the fleet action API of the control bot
CRED_TOOLS = ("httpBearerAuth", "fleet-tools-token")       # the agents call the fleet-tools MCP server


def cred(pair):
    return {pair[0]: {"id": "FLEET_CRED:" + pair[1], "name": pair[1]}}


class WF:
    def __init__(self, key, name, error=True, frequent=False):
        self.key, self.name = key, name
        self.nodes, self.connections = [], {}
        self.settings = {"executionOrder": "v1", "saveDataErrorExecution": "all", "saveDataSuccessExecution": "none" if frequent else "all",
                         "saveManualExecutions": False, "timezone": TZ, "executionTimeout": 300}
        if error:
            self.settings["errorWorkflow"] = "FLEET_WF:fleet-error"

    def add(self, name, type_, version, parameters, x, y, credentials=None, **flags):
        node = {"id": str(uuid.uuid5(NS, self.key + "/" + name)), "name": name, "type": type_, "typeVersion": version,
                "position": [x, y], "parameters": parameters}
        if credentials:
            node["credentials"] = credentials
        node.update(flags)
        self.nodes.append(node)
        return name

    def link(self, src, dst, output=0, kind="main"):
        lists = self.connections.setdefault(src, {}).setdefault(kind, [])
        while len(lists) <= output:
            lists.append([])
        lists[output].append({"node": dst, "type": kind, "index": 0})

    def build(self):
        return {"name": self.name, "nodes": self.nodes, "connections": self.connections, "settings": self.settings,
                "meta": {"generated_by": "scripts/gen_n8n.py. Do not edit this file by hand."}}


def code(wf, name, js, x, y, **flags):
    return wf.add(name, "n8n-nodes-base.code", 2, {"jsCode": js.strip() + "\n"}, x, y, **flags)


def http(wf, name, method, url, x, y, auth=None, body=None, timeout=15000, text=False, **flags):
    params = {"method": method, "url": url, "options": {"timeout": timeout}}
    if auth:
        params.update({"authentication": "genericCredentialType", "genericAuthType": auth[0]})
    if body is not None:
        params.update({"sendBody": True, "contentType": "json", "specifyBody": "json", "jsonBody": body})
    if text:
        params["options"]["response"] = {"response": {"neverError": True, "fullResponse": True, "responseFormat": "text"}}
    return wf.add(name, "n8n-nodes-base.httpRequest", 4.5, params, x, y, credentials=cred(auth) if auth else None, **flags)


def if_true(wf, name, field, x, y):
    cond = {"id": str(uuid.uuid5(NS, wf.key + "/" + name + "/cond")), "leftValue": "={{ %s }}" % field, "rightValue": "",
            "operator": {"type": "boolean", "operation": "true", "singleValue": True}}
    return wf.add(name, "n8n-nodes-base.if", 2.2, {"conditions": {"options": {"caseSensitive": True, "leftValue": "", "typeValidation": "loose", "version": 2},
                                                                 "conditions": [cond], "combinator": "and"}, "options": {}}, x, y)


def retry(n=3, wait=2000):
    return {"retryOnFail": True, "maxTries": n, "waitBetweenTries": wait}


